// A broad, browsable emoji bank for the page-icon picker, each entry tagged
// with a name + search keywords so the picker's search box can find an emoji
// by word (e.g. "heart", "money", "cat") — not just by pasting the glyph.
// Curated (not the full Unicode set) to stay dependency-free, but wide enough
// to pick a fitting icon. Extend a group's list to add more options.

export interface EmojiEntry {
  char: string;
  name: string;
  /** Lowercased search tokens (name words + extra synonyms). */
  keywords: string[];
}

export interface EmojiGroup {
  label: string;
  emojis: EmojiEntry[];
}

// [char, name, extra space-separated keywords?]
type Raw = [string, string, string?];

function group(label: string, raw: Raw[]): EmojiGroup {
  return {
    label,
    emojis: raw.map(([char, name, extra]) => ({
      char,
      name,
      keywords: Array.from(
        new Set(
          `${name} ${extra ?? ''}`
            .toLowerCase()
            .split(/[\s,]+/)
            .filter(Boolean)
        )
      ),
    })),
  };
}

