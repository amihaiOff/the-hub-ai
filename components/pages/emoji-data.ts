/** Flat list of every emoji across all groups. */
export const ALL_EMOJIS: EmojiEntry[] = EMOJI_GROUPS.flatMap((g) => g.emojis);

/**
 * Filter emojis by a free-text query, matching against name + keyword tokens
 * (substring match, so "mon" or "one" both find "money"). Multiple terms are
 * AND-ed. Returns everything for an empty query. Results are de-duplicated by
 * glyph (the same glyph can be listed under more than one group).
 */
export function searchEmojis(query: string): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_EMOJIS;
  const terms = q.split(/\s+/).filter(Boolean);
  const seen = new Set<string>();
  const out: EmojiEntry[] = [];
  for (const e of ALL_EMOJIS) {
    if (seen.has(e.char)) continue;
    // Every search term must match some keyword (prefix or substring).
    const ok = terms.every((t) => e.keywords.some((k) => k.includes(t)));
    if (ok) {
      seen.add(e.char);
      out.push(e);
    }
  }
  return out;
}
